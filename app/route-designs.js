export function routeDesign(stage) {
  const variant=Math.max(0,Math.min(2,Number(stage.variant)||0)),region=stage.region||'france';
  const headings=DESIGNS[region]?.[variant]||DESIGNS.france[variant];
  let seed=7919;for(const letter of `${region}-${variant}`)seed=(Math.imul(seed,33)+letter.charCodeAt(0))>>>0;
  const random=()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return seed/4294967296};
  const technical=['alps','monte','romania'].includes(region),desert=region==='dakar';
  const runs=headings.map((_,i)=>i===0?88:(desert?125:technical?104:112)+random()*(desert?105:88));
  return {headings,runs,transition:desert?85:technical?42:58,waves:3+variant,phase:(region.length*.47+variant*.71),descending:variant===1};
}
